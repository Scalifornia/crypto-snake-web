export function getProfessionOptions(language: Locale) {
  const options = professionOptions[language as BaseLocale] ?? professionOptions.en;
  const extraOptions = extraProfessionOptions[language as BaseLocale] ?? extraProfessionOptions.en;
  return Array.from(new Set([...options, ...extraOptions])).sort((first, second) => first.localeCompare(second, language));
}
